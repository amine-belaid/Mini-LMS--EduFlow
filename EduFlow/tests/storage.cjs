const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.join(__dirname, '..');
const values = new Map();
const localStorage = { getItem: key => values.get(key) ?? null, setItem: (key,value) => values.set(key,value) };
const context = vm.createContext({ window: {}, localStorage });
for (const file of ['data','storage']) vm.runInContext(fs.readFileSync(path.join(root,`js/${file}.js`),'utf8'),context);
const storage = context.window.EduFlowStorage;
assert.equal(storage.getCourseProgress('html-css',12).enrolled,false);
assert.equal(storage.saveLesson('html-css',0,12).success,true);
assert.equal(storage.getCourseProgress('html-css',12).enrolled,true);
assert.equal(storage.getCourseProgress('html-css',12).percent,0);
storage.saveLesson('html-css',0,12,true);
storage.saveLesson('html-css',0,12,true);
assert.equal(storage.getCourseProgress('html-css',12).completed.length,1);
assert.equal(storage.getActivities().length,2);
storage.saveLesson('html-css',1,12,true);
assert.equal(storage.getCourseProgress('html-css',12).lastLesson,1);
for(let i=0;i<12;i++) storage.saveLesson('html-css',i,12,true);
assert.equal(storage.getCourseProgress('html-css',12).percent,100);
storage.saveLesson('html-css',4,12,false);
assert.equal(storage.getCourseProgress('html-css',12).completed.length,11);
assert.equal(storage.saveLesson('html-css',-1,12,true).success,false);
assert.equal(storage.saveLesson('html-css',12,12,true).success,false);
assert.equal(storage.saveLesson('__proto__',0,12,true).success,false);
assert.equal(storage.toggleFavorite('sql').isFavorite,true);
assert.equal(storage.toggleFavorite('sql').isFavorite,false);
values.set(storage.progressKey,'invalid json');
assert.equal(storage.getCourseProgress('html-css',12).percent,0);
values.set(storage.progressKey,JSON.stringify({'html-css':{completed:[0,0,99,-1,'1'],lastLesson:100}}));
assert.equal(storage.getCourseProgress('html-css',12).completed.length,1);
assert.equal(storage.getCourseProgress('html-css',12).lastLesson,0);
localStorage.setItem = () => { throw new Error('unavailable'); };
assert.equal(storage.saveLesson('sql',0,8,true).success,false);
assert.equal(storage.toggleFavorite('sql').success,false);
const data = context.window.EduFlowData;
assert.equal(data.courses.length,8);
assert.equal(new Set(data.courses.map(course => course.id)).size,8);
for(const course of data.courses) {
    const lessons = data.getLessons(course);
    assert.ok(lessons.length > 0);
    for(let i=0;i<lessons.length;i++) assert.ok(data.getLessonContent(course,i).exercise);
    for(const asset of [course.image,course.instructor.image]) assert.ok(fs.existsSync(path.join(root,asset)),`Missing ${asset}`);
}
console.log('OK : progression, reprise, favoris, corruption, erreurs et données des 8 cours.');
